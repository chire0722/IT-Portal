using IT_Form.Data;
using IT_Form.Application.Features.StandardSoftware;
using IT_Form.Services;
using MediatR;

namespace IT_Form.Application.Features.StandardSoftware.QuickAllocateSubscriptionSeat
{
    /// <summary>
    /// Handles the QuickAllocateSubscriptionSeatCommand command workflow.
    /// </summary>
    public sealed class QuickAllocateSubscriptionSeatCommandHandler : IRequestHandler<QuickAllocateSubscriptionSeatCommand, QuickAllocateSubscriptionSeatResult>
    {
        private readonly ApplicationDbContext _context;
        public QuickAllocateSubscriptionSeatCommandHandler(
            ApplicationDbContext context,
            ILicenseEncryptionService encryptionService)
        {
            _context = context;
        }

        /// <summary>
        /// Executes the request and returns the workflow result.
        /// </summary>
        public async Task<QuickAllocateSubscriptionSeatResult> Handle(QuickAllocateSubscriptionSeatCommand request, CancellationToken cancellationToken)
        {
            var license = await _context.SoftwareLicenses.FindAsync(new object[] { request.SoftwareId }, cancellationToken);
            if (license == null)
            {
                return new QuickAllocateSubscriptionSeatResult(QuickAllocateSubscriptionSeatStatus.NotFound, "License not found.");
            }

            if (!license.IsSubscription)
            {
                return new QuickAllocateSubscriptionSeatResult(QuickAllocateSubscriptionSeatStatus.NotSubscription, "Only applicable for subscriptions.");
            }

            license.ContractLimit += 1;
            var seatSyncResult = await SoftwareLicenseSeatSyncSupport.SyncAutoGeneratedSeatsAsync(_context, license, cancellationToken);
            if (!seatSyncResult.IsValid)
            {
                return new QuickAllocateSubscriptionSeatResult(
                    QuickAllocateSubscriptionSeatStatus.NotSubscription,
                    seatSyncResult.ErrorMessage ?? "Unable to add seat.");
            }

            await _context.SaveChangesAsync(cancellationToken);

            return new QuickAllocateSubscriptionSeatResult(QuickAllocateSubscriptionSeatStatus.Allocated, "Seat allocated.");
        }
    }
}
