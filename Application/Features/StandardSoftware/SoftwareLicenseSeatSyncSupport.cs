using IT_Form.Data;
using IT_Form.Models;
using Microsoft.EntityFrameworkCore;

namespace IT_Form.Application.Features.StandardSoftware;

internal static class SoftwareLicenseSeatSyncSupport
{
    public static void NormalizeLicenseSettings(SoftwareLicense license)
    {
        if (license.IsFree)
        {
            license.IsSubscription = false;
            license.ExpiryDate = null;
            license.ContractLimit = 0;
        }
        else if (!license.IsSubscription)
        {
            license.ContractLimit = 0;
        }

        if (license.ContractLimit < 0)
        {
            license.ContractLimit = 0;
        }
    }

    public static async Task<SoftwareLicenseSeatSyncResult> SyncAutoGeneratedSeatsAsync(
        ApplicationDbContext context,
        SoftwareLicense license,
        CancellationToken cancellationToken)
    {
        NormalizeLicenseSettings(license);

        await context.Entry(license)
            .Collection(item => item.Keys)
            .LoadAsync(cancellationToken);

        if (!license.IsSubscription || license.IsFree)
        {
            license.TotalLicenses = license.Keys.Count;
            return SoftwareLicenseSeatSyncResult.Success();
        }

        var targetSeatCount = Math.Max(license.ContractLimit, 0);
        var assignedSeatCount = license.Keys.Count(key => key.IsAssigned);
        if (assignedSeatCount > targetSeatCount)
        {
            return SoftwareLicenseSeatSyncResult.Invalid(
                $"Cannot reduce seat limit below {assignedSeatCount} assigned seat(s). Unassign some seats first.");
        }

        var currentSeatCount = license.Keys.Count;
        if (currentSeatCount < targetSeatCount)
        {
            for (var index = 0; index < targetSeatCount - currentSeatCount; index++)
            {
                license.Keys.Add(CreateSeatPlaceholder(license.Id));
            }
        }
        else if (currentSeatCount > targetSeatCount)
        {
            var seatsToRemove = currentSeatCount - targetSeatCount;
            var removableKeys = license.Keys
                .Where(key => !key.IsAssigned)
                .OrderByDescending(key => key.CreatedAt)
                .Take(seatsToRemove)
                .ToList();

            if (removableKeys.Count != seatsToRemove)
            {
                return SoftwareLicenseSeatSyncResult.Invalid(
                    "Unable to reduce seat limit because too many seats are already assigned.");
            }

            context.SoftwareKeys.RemoveRange(removableKeys);
        }

        license.TotalLicenses = targetSeatCount;
        return SoftwareLicenseSeatSyncResult.Success();
    }

    public static int GetAvailableAssignmentCount(
        bool isFree,
        bool hasSeatRows,
        int availableSeatRows,
        int issuedAssignments,
        int contractLimit)
    {
        if (isFree)
        {
            return int.MaxValue;
        }

        return hasSeatRows
            ? Math.Max(availableSeatRows, 0)
            : Math.Max(contractLimit - issuedAssignments, 0);
    }

    private static SoftwareKey CreateSeatPlaceholder(int softwareLicenseId)
    {
        return new SoftwareKey
        {
            SoftwareLicenseId = softwareLicenseId,
            KeyValue = $"Seat-{Guid.NewGuid().ToString("N")[..8]}",
            IsAssigned = false,
            CreatedAt = DateTime.UtcNow
        };
    }
}

internal sealed record SoftwareLicenseSeatSyncResult(bool IsValid, string? ErrorMessage)
{
    public static SoftwareLicenseSeatSyncResult Success()
        => new(true, null);

    public static SoftwareLicenseSeatSyncResult Invalid(string message)
        => new(false, message);
}
