using IT_Form.Data;
using FluentValidation;
using FluentValidation.Results;
using IT_Form.Application.Common.Abstractions;
using IT_Form.Application.Common.Support;
using IT_Form.Application.Features.StandardSoftware;
using IT_Form.Models;
using MediatR;
using Microsoft.EntityFrameworkCore;

namespace IT_Form.Application.Features.StandardSoftware.EditSoftwareLicense
{
    public sealed class EditSoftwareLicenseCommandHandler : IRequestHandler<EditSoftwareLicenseCommand, EditSoftwareLicenseResult>
    {
        private readonly ApplicationDbContext _context;
        private readonly ICurrentUserAccessor _currentUserAccessor;

        public EditSoftwareLicenseCommandHandler(ApplicationDbContext context, ICurrentUserAccessor currentUserAccessor)
        {
            _context = context;
            _currentUserAccessor = currentUserAccessor;
        }

        public async Task<EditSoftwareLicenseResult> Handle(EditSoftwareLicenseCommand request, CancellationToken cancellationToken)
        {
            var license = await _context.SoftwareLicenses
                .Include(item => item.SoftwareLicenseCompanies)
                .FirstOrDefaultAsync(item => item.Id == request.Id, cancellationToken);
            if (license == null)
            {
                return new EditSoftwareLicenseResult(EditSoftwareLicenseStatus.NotFound, "Version not found.");
            }

            if (request.IsSubscription && !request.IsFree && !request.ExpiryDate.HasValue)
            {
                return new EditSoftwareLicenseResult(EditSoftwareLicenseStatus.InvalidSubscriptionExpiry, "Expiry Date is required for subscription version.");
            }

            await EnsureExistingLicenseIsInScopeAsync(license.SoftwareLicenseCompanies.Select(link => link.CompanyId), cancellationToken);
            await EnsureRequestedCompaniesAreAllowedAsync(request.SelectedCompanyIds, cancellationToken);

            license.SoftwareName = request.SoftwareName;
            license.Description = request.Description;
            license.IsSubscription = request.IsSubscription;
            license.IsFree = request.IsFree;
            license.ExpiryDate = request.ExpiryDate;
            license.ContractLimit = request.ContractLimit ?? 0;
            license.VendorName = request.VendorName;
            license.SupportContact = request.SupportContact;

            var currentCompanyIds = license.SoftwareLicenseCompanies
                .Select(link => link.CompanyId)
                .ToHashSet();

            var selectedCompanyIds = request.SelectedCompanyIds
                .Distinct()
                .ToHashSet();

            var companyLinksToRemove = license.SoftwareLicenseCompanies
                .Where(link => !selectedCompanyIds.Contains(link.CompanyId))
                .ToList();

            if (companyLinksToRemove.Count > 0)
            {
                _context.SoftwareLicenseCompanies.RemoveRange(companyLinksToRemove);
            }

            var companyLinksToAdd = selectedCompanyIds
                .Except(currentCompanyIds)
                .Select(companyId => new SoftwareLicenseCompany
                {
                    SoftwareLicenseId = license.Id,
                    CompanyId = companyId
                })
                .ToList();

            if (companyLinksToAdd.Count > 0)
            {
                await _context.SoftwareLicenseCompanies.AddRangeAsync(companyLinksToAdd, cancellationToken);
            }

            SoftwareLicenseSeatSyncSupport.NormalizeLicenseSettings(license);
            var seatSyncResult = await SoftwareLicenseSeatSyncSupport.SyncAutoGeneratedSeatsAsync(_context, license, cancellationToken);
            if (!seatSyncResult.IsValid)
            {
                return new EditSoftwareLicenseResult(
                    EditSoftwareLicenseStatus.InvalidSeatLimit,
                    seatSyncResult.ErrorMessage ?? "Invalid seat limit.");
            }

            await _context.SaveChangesAsync(cancellationToken);
            return new EditSoftwareLicenseResult(EditSoftwareLicenseStatus.Updated, "Version updated.");
        }

        private async Task EnsureExistingLicenseIsInScopeAsync(IEnumerable<int> existingCompanyIds, CancellationToken cancellationToken)
        {
            if (ItAdminCompanyScopeSupport.HasGlobalAccess(_currentUserAccessor.User))
            {
                return;
            }

            var existingIds = existingCompanyIds.ToArray();
            if (existingIds.Length == 0)
            {
                throw new ValidationException([new ValidationFailure(string.Empty, "You can only modify software versions within your own company scope.")]);
            }

            var accessibleCompanyIds = await ItAdminCompanyScopeSupport.LoadAccessibleCompanyIdsAsync(_context, _currentUserAccessor.User, cancellationToken)
                ?? [];
            if (!existingIds.All(accessibleCompanyIds.Contains))
            {
                throw new ValidationException([new ValidationFailure(string.Empty, "You can only modify software versions within your own company scope.")]);
            }
        }

        private async Task EnsureRequestedCompaniesAreAllowedAsync(IEnumerable<int> selectedCompanyIds, CancellationToken cancellationToken)
        {
            var requestedCompanyIds = selectedCompanyIds
                .Distinct()
                .ToArray();

            if (requestedCompanyIds.Length == 0)
            {
                if (!ItAdminCompanyScopeSupport.HasGlobalAccess(_currentUserAccessor.User))
                {
                    throw new ValidationException([new ValidationFailure(string.Empty, "Select at least one company for this software version.")]);
                }

                return;
            }

            var isAssignable = await ItAdminCompanyScopeSupport.AreRequestedCompanyIdsAssignableAsync(
                _context,
                _currentUserAccessor.User,
                requestedCompanyIds,
                cancellationToken);

            if (!isAssignable)
            {
                throw new ValidationException([new ValidationFailure(string.Empty, "You can only assign software versions to your own company scope.")]);
            }
        }
    }
}
